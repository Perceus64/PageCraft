#!/usr/bin/env python3
"""Builds vendor/fonts/*, vendor/fonts/manifest.json and css/fonts.css from @fontsource packages.
Needs: npm i (for node_modules/@fontsource/*) and `pip install fonttools brotli`.
.woff is used by the browser (on-screen editor); .ttf (converted) is embedded into exported PDFs,
because pdf-lib's subsetter mishandles Arabic composite glyphs."""
import json, os, shutil
from fontTools.ttLib import TTFont

SRC = 'node_modules/@fontsource/'; OUT = 'vendor/fonts/'
WEIGHTS = (400, 700)
RANGES = {
  'latin': 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
  'cyrillic': 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116',
  'greek': 'U+0370-0377,U+037A-037F,U+0384-038A,U+038C,U+038E-03A1,U+03A3-03FF',
  'arabic': 'U+0600-06FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC',
}
# family -> label, {script: fontsource package}   (a script that a package lacks falls back to "sans" at runtime)
FAMILIES = {
  'sans':  ('Sans',        {'latin': 'noto-sans', 'latin-ext': 'noto-sans', 'cyrillic': 'noto-sans', 'greek': 'noto-sans', 'arabic': 'noto-sans-arabic'}),
  'serif': ('Serif',       {'latin': 'noto-serif', 'latin-ext': 'noto-serif', 'cyrillic': 'noto-serif', 'greek': 'noto-serif', 'arabic': 'noto-naskh-arabic'}),
  'mono':  ('Monospace',   {'latin': 'noto-sans-mono', 'latin-ext': 'noto-sans-mono', 'cyrillic': 'noto-sans-mono', 'greek': 'noto-sans-mono'}),
  'hand':  ('Handwriting', {'latin': 'caveat', 'latin-ext': 'caveat', 'cyrillic': 'caveat', 'arabic': 'noto-naskh-arabic'}),
}

shutil.rmtree(OUT, ignore_errors=True); os.makedirs(OUT)
made = {}   # (package, script, weight) -> filename stem, so shared fonts are written once
manifest = {'families': {}, 'files': {}}
css = ['/* generated by scripts/build_fonts.py — do not edit */']
for fam, (label, scripts) in FAMILIES.items():
    manifest['families'][fam] = label; manifest['files'][fam] = {}
    for script, pkg in scripts.items():
        manifest['files'][fam][script] = {}
        for w in WEIGHTS:
            key = (pkg, script, w)
            if key not in made:
                stem = f'{pkg}-{script}-{w}'; made[key] = stem
                src = f'{SRC}{pkg}/files/{pkg}-{script}-{w}-normal.woff'
                shutil.copy(src, f'{OUT}{stem}.woff')
                f = TTFont(src); f.flavor = None; f.save(f'{OUT}{stem}.ttf')
            stem = made[key]
            manifest['files'][fam][script][str(w)] = stem
            css.append(f"@font-face {{ font-family: 'PC-{fam}'; font-weight: {w}; font-display: swap; src: url('../vendor/fonts/{stem}.woff') format('woff'); unicode-range: {RANGES[script]}; }}")
json.dump(manifest, open(OUT + 'manifest.json', 'w'), indent=1)
open('css/fonts.css', 'w').write('\n'.join(css) + '\n')
print(len(made), 'font files;', sum(os.path.getsize(OUT + f) for f in os.listdir(OUT)) // 1024, 'KB')
